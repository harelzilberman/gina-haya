// Shape of a raw row from biodynamic_calendar_variants (the legacy
// biodynamic_calendar columns plus the variant fields)
interface CalendarRow {
  date: string;
  ascending_descending: 'ascending' | 'descending';
  ascending_descending_he: string;
  phase_transition_time: string | null;
  node_active: boolean;
  node_blackout_start: string | null;
  node_blackout_end: string | null;
  perigee_active: boolean;
  prep_500_recommended: boolean;
  prep_501_recommended: boolean;
  moon_sign: string;
  moon_sign_he: string;
  day_type: 'fruit' | 'root' | 'flower' | 'leaf';
  day_type_he: string;
  day_type_change_time: string | null;
  moon_phase_pct: number;
  moon_phase_name: string;
  moon_phase_name_he: string;
  moon_phase_angle?: number;
  moon_phase_he?: string;
  planting_score: number;
  score_colour: 'green' | 'yellow' | 'orange' | 'red' | 'black';
  moonrise_time: string | null;
  moonset_time: string | null;
  mon_daily_summary: string;
  mon_daily_summary_en?: string;
  // biodynamic_calendar_variants only
  utc_offset_hours?: number;
  hemisphere?: 'north' | 'south';
  transitions?: CalendarTransition[];
  node_exact_utc?: string | null;
}

function toCalendarDay(row: CalendarRow): BiodynamicDay {
  return {
    date: row.date,
    ascendingDescending: row.ascending_descending,
    ascendingDescendingHe: row.ascending_descending_he,
    phaseTransitionTime: row.phase_transition_time,
    nodeActive: row.node_active,
    nodeBlackoutStart: row.node_blackout_start,
    nodeBlackoutEnd: row.node_blackout_end,
    perigeeActive: row.perigee_active,
    prep500Recommended: row.prep_500_recommended,
    prep501Recommended: row.prep_501_recommended,
    moonSign: row.moon_sign,
    moonSignHe: row.moon_sign_he,
    dayType: row.day_type,
    dayTypeHe: row.day_type_he,
    dayTypeChangeTime: row.day_type_change_time,
    moonPhasePct: row.moon_phase_pct,
    moonPhaseName: row.moon_phase_name,
    moonPhaseNameHe: row.moon_phase_name_he,
    moonPhaseAngle: row.moon_phase_angle,
    moonPhaseHe: row.moon_phase_he,
    plantingScore: row.planting_score,
    scoreColour: row.score_colour,
    moonriseTime: row.moonrise_time,
    moonsetTime: row.moonset_time,
    chupChuDailySummary: row.mon_daily_summary,
    chupChuDailySummaryEn: row.mon_daily_summary_en,
    // Overwritten in getVariantDays with the local-day overlap.
    nodeBlackoutToday: row.node_active,
  };
}

function toVariantDay(row: CalendarRow, timezone: string): BiodynamicDay {
  return {
    ...toCalendarDay(row),
    transitions: Array.isArray(row.transitions) ? row.transitions : [],
    utcOffsetHours: row.utc_offset_hours,
    hemisphere: row.hemisphere,
    timezone,
  };
}

/**
 * Real values for the four fields the legacy table only had placeholders for
 * (seed-calendar-placeholder.ts wrote fixed "T08:00"/"T14:00" times; the
 * Python generator never computed them), derived from the variant row:
 *   day_type_change_time    = first sign_change inside the local day
 *   phase_transition_time   = the new/full moon moment inside the local day
 *   node_blackout_start/end = node_exact_utc -/+ NODE_BLACKOUT_HOURS / 2
 * All UTC ISO timestamps. Mutates and returns the row.
 */
function deriveVariantTimes<T extends CalendarRow>(row: T): T {
  const transitions = Array.isArray(row.transitions) ? row.transitions : [];
  const firstSign = transitions.find(t => t.type === 'sign_change');
  const phase     = transitions.find(t => t.type === 'new_moon' || t.type === 'full_moon');
  row.day_type_change_time  = firstSign ? firstSign.at_utc : null;
  row.phase_transition_time = phase ? phase.at_utc : null;
  const nodeMs = row.node_exact_utc ? Date.parse(row.node_exact_utc) : NaN;
  if (Number.isFinite(nodeMs)) {
    const half = (NODE_BLACKOUT_HOURS / 2) * 3_600_000;
    row.node_blackout_start = new Date(nodeMs - half).toISOString();
    row.node_blackout_end   = new Date(nodeMs + half).toISOString();
  } else {
    row.node_blackout_start = null;
    row.node_blackout_end   = null;
  }
  return row;
}

// ── Timezone / hemisphere variants — the only calendar read path ─────────────
//
// biodynamic_calendar_variants: one row per (date, utc_offset_hours,
// hemisphere). The variant is resolved PER DATE from the location's timezone,
// so a range that crosses a DST change reads two variants.
//
// Every calendar read in the API goes through here. With no location, use
// ISRAEL_CALENDAR_LOCATION (Asia/Jerusalem, north): its rows are verified
// identical to the legacy biodynamic_calendar table. That table is still
// generated by the "Calendar" GitHub Action as a backup for one more month.
// The API reads it only for dates that have no variant row yet (variants
// start 2026-11-12) — see legacyFallbackRows below.

export interface CalendarLocation {
  /** IANA zone (null → Asia/Jerusalem). */
  timezone: string | null;
  /** Latitude (null → north). */
  latitude: number | null;
}

/** No location → Israel / north, exactly as before. */
export const ISRAEL_CALENDAR_LOCATION: CalendarLocation = Object.freeze({
  timezone: DEFAULT_CALENDAR_TIMEZONE,
  latitude: null,
});

let warnedMissingVariants = false;

/** All "YYYY-MM-DD" dates from..to inclusive. */
export function datesBetween(from: string, to: string): string[] {
  const out: string[] = [];
  const end = Date.parse(`${to}T00:00:00Z`);
  for (let t = Date.parse(`${from}T00:00:00Z`); t <= end; t += 86_400_000) {
    out.push(new Date(t).toISOString().slice(0, 10));
  }
  return out;
}

/**
 * A raw calendar row (snake_case, derived times filled in). fromVariant is
 * false for a legacy-table fallback row (Israel, no transitions).
 */
export type RawCalendarRow = CalendarRow & { [column: string]: unknown; fromVariant: boolean };

let warnedLegacyFallback = false;

/**
 * TRANSITION ONLY — dates with no variant row (before 2026-11-12, when the
 * variants start, until they are backfilled with the "Calendar" workflow's
 * start_date/days inputs) fall back to the legacy biodynamic_calendar row:
 * Israel noon, northern hemisphere, no transitions. The placeholder-only time
 * fields (day_type_change_time, phase_transition_time, node_blackout_*) are
 * cleared — generate_calendar.py never computed them.
 *
 * TODO(calendar-legacy): remove this fallback together with the legacy
 * biodynamic_calendar table (and its generation in the workflow) once the
 * variants backfill is confirmed to cover every date the app reads.
 */
async function legacyFallbackRows(dates: string[]): Promise<Map<string, RawCalendarRow>> {
  const out = new Map<string, RawCalendarRow>();
  if (dates.length === 0) return out;
  const sorted = [...dates].sort();
  for (let i = 0; i < sorted.length; i += MAX_DATES_PER_QUERY) {
    const chunk = sorted.slice(i, i + MAX_DATES_PER_QUERY);
    const { data, error } = await db
      .from('biodynamic_calendar')
      .select('*')
      .gte('date', chunk[0])
      .lte('date', chunk[chunk.length - 1]);
    if (error) {
      console.warn('[calendar] legacy biodynamic_calendar fallback failed:', error.message);
      return out;
    }
    const wanted = new Set(chunk);
    for (const row of data ?? []) {
      if (!wanted.has(row.date)) continue;
      out.set(row.date, {
        ...row,
        day_type_change_time: null,
        phase_transition_time: null,
        node_blackout_start: null,
        node_blackout_end: null,
        transitions: [],
        fromVariant: false,
      });
    }
  }
  if (out.size > 0 && !warnedLegacyFallback) {
    warnedLegacyFallback = true;
    console.warn(`[calendar] ${out.size} date(s) without variant rows (first ${[...out.keys()].sort()[0]}) served from the legacy biodynamic_calendar. Backfill the variants with the "Calendar" workflow (start_date/days).`);
  }
  return out;
}

/** PostgREST caps a response at 1000 rows; long ranges are queried in chunks. */
const MAX_DATES_PER_QUERY = 900;

/**
 * Raw (snake_case) variant rows for the given dates, keyed by date. Dates
 * without a variant row fall back to the legacy table (transition only, see
 * legacyFallbackRows); dates in neither are absent (logged once per process).
 * For callers that format DB rows directly (Chupchu, trackers, home).
 */
export async function getVariantRawRows(
  dates: string[],
  loc: CalendarLocation = ISRAEL_CALENDAR_LOCATION,
): Promise<Map<string, RawCalendarRow>> {
  const byDate = new Map<string, RawCalendarRow>();
  if (dates.length === 0) return byDate;

  const groups = new Map<string, { variant: CalendarVariant; dates: string[] }>();
  for (const date of [...new Set(dates)].sort()) {
    const variant = resolveVariant(date, loc.timezone, loc.latitude);
    const key = `${variant.utcOffsetHours}:${variant.hemisphere}`;
    const g = groups.get(key) ?? { variant, dates: [] };
    g.dates.push(date);
    groups.set(key, g);
  }

  for (const { variant, dates: groupDates } of groups.values()) {
    for (let i = 0; i < groupDates.length; i += MAX_DATES_PER_QUERY) {
      const chunk = groupDates.slice(i, i + MAX_DATES_PER_QUERY);
      const { data, error } = await db
        .from('biodynamic_calendar_variants')
        .select('*')
        .eq('utc_offset_hours', variant.utcOffsetHours)
        .eq('hemisphere', variant.hemisphere)
        .gte('date', chunk[0])
        .lte('date', chunk[chunk.length - 1]);
      if (error) throw error;
      const wanted = new Set(chunk);
      for (const row of data ?? []) {
        if (wanted.has(row.date)) byDate.set(row.date, deriveVariantTimes({ ...row, fromVariant: true as const }));
      }
    }
  }

  const noVariant = [...new Set(dates)].filter(d => !byDate.has(d));
  if (noVariant.length > 0) {
    for (const [date, row] of await legacyFallbackRows(noVariant)) byDate.set(date, row);
  }

  const missing = dates.filter(d => !byDate.has(d));
  if (missing.length > 0 && !warnedMissingVariants) {
    warnedMissingVariants = true;
    console.warn(`[calendar] no biodynamic_calendar_variants rows for ${missing.length} date(s) (first ${missing[0]}). Run the "Calendar" GitHub Action.`);
  }
  return byDate;
}

/**
 * Calendar days for the given dates, ordered by date; dates without a row are
 * omitted. `legacyShape` leaves out the variant-only fields (transitions,
 * utcOffsetHours, hemisphere, timezone): the response shape old app versions
 * got from the parameterless endpoints.
 */
export async function getVariantDays(
  dates: string[],
  loc: CalendarLocation = ISRAEL_CALENDAR_LOCATION,
  opts: { legacyShape?: boolean } = {},
): Promise<BiodynamicDay[]> {
  if (dates.length === 0) return [];
  const tz = loc.timezone ?? DEFAULT_CALENDAR_TIMEZONE;
  const rows = await getVariantRawRows(dates, loc);
  return [...new Set(dates)].sort()
    .filter(d => rows.has(d))
    .map(d => {
      const row = rows.get(d)!;
      // Legacy fallback rows: same mapper, no variant fields.
      const day = opts.legacyShape || !row.fromVariant ? toCalendarDay(row) : toVariantDay(row, tz);
      day.nodeBlackoutToday = row.fromVariant ? blackoutOverlapsLocalDay(day, d, tz) : row.node_active;
      return day;
    });
}

/**
 * nodeBlackoutToday: [nodeBlackoutStart, nodeBlackoutEnd] overlaps the local
 * day [00:00, 24:00) of `date` in `tz`. Unlike nodeActive (node within ~6 h of
 * local noon — feeds the planting score, kept as is), this is also true on the
 * neighbouring day when the ±12 h window spills into it.
 */
function blackoutOverlapsLocalDay(day: BiodynamicDay, date: string, tz: string): boolean {
  if (!day.nodeBlackoutStart || !day.nodeBlackoutEnd) return false;
  const start = Date.parse(day.nodeBlackoutStart);
  const end   = Date.parse(day.nodeBlackoutEnd);
  const dayStart = Date.parse(localDateToUTCMidnight(date, tz));
  const dayEnd   = Date.parse(localDateToUTCMidnight(addDaysISO(date, 1), tz));
  return start < dayEnd && end > dayStart;
}

/** One calendar day in a location's variant, or null. */
export async function getVariantDay(
  date: string,
  loc: CalendarLocation = ISRAEL_CALENDAR_LOCATION,
  opts: { legacyShape?: boolean } = {},
): Promise<BiodynamicDay | null> {
  const [day] = await getVariantDays([date], loc, opts);
  return day ?? null;
}

/**
 * The first `limit` rows from `fromDate` (inclusive) within `horizonDays`
 * that match `predicate`, variant resolved per date (DST-safe). Replaces the
 * old "filter + order + limit" queries on the legacy table.
 */
export async function findVariantRawRows(
  fromDate: string,
  horizonDays: number,
  loc: CalendarLocation,
  predicate: (row: RawCalendarRow) => boolean,
  limit: number,
): Promise<RawCalendarRow[]> {
  const last = new Date(Date.parse(`${fromDate}T00:00:00Z`) + (horizonDays - 1) * 86_400_000)
    .toISOString().slice(0, 10);
  const dates = datesBetween(fromDate, last);
  const rows = await getVariantRawRows(dates, loc);
  const out: RawCalendarRow[] = [];
  for (const d of dates) {
    const row = rows.get(d);
    if (row && predicate(row)) {
      out.push(row);
      if (out.length >= limit) break;
    }
  }
  return out;
}
